#include <stdio.h>

int main()
{
    // 桶数组：下标即数字，值为 1 表示该数字出现过（自动去重）
    int a[1001] = {0};
    int n;          // 输入的随机数个数
    int b;          // 临时存放当前读入的数
    int ans = 0;    // 去重后剩余的个数

    scanf("%d", &n);
    // 逐个读入 n 个数，用桶标记
    for(int i = 1; i <= n; i++){
        scanf("%d", &b);        // 注意格式串末尾不能有空格，否则会卡住
        if (a[b] == 0){         // 第一次出现该数
            a[b] = 1;           // 标记为已出现
            ans ++;             // 计数 +1
        }
    }

    // 第一行：输出去重后的个数
    printf("%d\n", ans);
    // 第二行：从 1 到 1000 顺序扫描桶数组，遇到标记的就输出
    // 由于下标天然升序，所以输出结果自动有序
    for(int i = 1; i <= 1000; i++){
        if (a[i] == 1){
            printf("%d ", i);   // 输出的是下标 i（即原数字本身），不是 a[i]
        }
    }
    return 0;
}