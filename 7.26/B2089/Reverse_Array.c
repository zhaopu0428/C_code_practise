#include <stdio.h>
int main()
{
    int n;
    scanf("%d", &n);
    int a[101]={0};
    for (int i = 1; i <= n; i++)
    {
        scanf("%d", &a[i]);
        /*
        printf("%d ", a[i]);
        在 C 语言编程中，`scanf` 格式字符串的
        一个小陷阱会导致程序在本地终端运行时"卡住"不输出：
        当你在 `scanf` 的格式说明符（如 `%d`）后面多写了一个空格
        （即 `"%d "`）时，程序读完目标数据后会继续等待输入非空白字符才肯结束读取；
        在线评测系统因为是通过重定向一次性注入全部输入（遇到 EOF 标志即结束），
        所以不会触发这个问题，而在本地交互式终端中，程序就会一直卡在等待状态，
        看起来像是"跑很久都不输出"。修复方法就是把 `%d` 后面的空格去掉即可。
        */
    }
    for (int i = n; i >= 1; i--)
    {
        printf("%d ", a[i]);
    }
    return 0;
}