#include <stdio.h>
int main()
{
    int a, b;
    char op;
    scanf("%d %c %d", &a, &op, &b);
    switch (op)
    {
    case '+': printf("%d\n", a + b); break;
    case '-': printf("%d\n", a - b); break;
    case '*': printf("%d\n", a * b); break;
    case '/': printf("%d\n", a / b); break;
    case '%': printf("%d\n", a % b); break;
    }
    return 0;
}
/*
因为 `scanf` 的格式串中，`%d` 和 `%c` 之间的**空格**起了关键作用：

## scanf 的读取过程

输入 `32+64`，格式串 `"%d %c %d"`：

```
第1步：%d → 自动跳过空白，读数字 "32"，遇到 '+' 停止
         此时：a = 32，指针停在 '+'

第2步：空格 → 跳过空白字符（这里没有空白，直接跳过）
         指针仍在 '+'

第3步：%c → 读取当前字符 '+'
         此时：op = '+'，指针停在 '6'

第4步：空格 → 跳过空白字符（这里没有空白，直接跳过）
         指针仍在 '6'

第5步：%d → 读数字 "64"
         此时：b = 64
```

## 如果格式串中没有空格呢？

假设格式串是 `"%d%c%d"`（没有空格）：

```
第1步：%d → 读 "32"，指针停在 '+'
第2步：%c → 读 '+'（正确）
第3步：%d → 读 "64"（正确）
```

**对于 `32+64` 这种没空格的情况，结果是一样的。**

但如果输入是 `32 + 64`（有空格），格式串 `"%d%c%d"` 就会**读错**：

```
第1步：%d → 读 "32"，指针停在 ' '
第2步：%c → 读 ' '（空格！不是 '+'）
第3步：%d → 读 "+64"，但 + 不是数字，a 读成 0 或出错
```

## 总结

格式串中的**空格** = "跳过任意数量的空白字符（包括零个）"。所以：

- `"%d %c %d"` → 既能处理 `32+64`，也能处理 `32 + 64`
- `"%d%c%d"` → 只能处理 `32+64`，遇到 `32 + 64` 就失败了

这就是为什么加了空格后两种输入都能正确读取。
*/